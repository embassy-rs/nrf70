/// How long the RPU gets to answer the init command and interface changes.
const EVENT_TIMEOUT: Duration = Duration::from_secs(5);
/// A scan covers every 2.4 GHz and 5 GHz channel, which takes a few seconds.
const SCAN_TIMEOUT: Duration = Duration::from_secs(30);
/// The RPU raises HOST_IRQ when it has events. The event queue is read this often as well, in
/// case an interrupt goes missing.
const IRQ_POLL_PERIOD: Duration = Duration::from_millis(50);
/// In low power mode, how long after the last bus access the RPU may sleep again (NCS
/// `NRF70_RPU_PS_IDLE_TIMEOUT_MS`).
const RPU_IDLE_TIMEOUT: Duration = Duration::from_millis(10);
/// How long the RPU gets to wake up (NCS `RPU_PS_WAKE_TIMEOUT_S`). The data sheet gives 6.7 ms.
const RPU_WAKE_TIMEOUT: Duration = Duration::from_secs(1);
/// How long a deauthentication frame gets to leave before the chip is turned off.
const POWER_OFF_DELAY: Duration = Duration::from_millis(20);
/// How many access points of a network a join tries in turn, best first.
const CANDIDATES: usize = 4;
/// How many channels of a network are remembered for the next join.
const KNOWN_CHANNELS: usize = 4;
/// A scan of the remembered channels takes 50 ms per channel, 150 ms where the RPU may only
/// listen. Past this, the join falls back to the scan of every channel.
const KNOWN_SCAN_TIMEOUT: Duration = Duration::from_secs(2);
/// Scan results buffered between the runner and a [`Scanner`].
const SCAN_RESULTS_DEPTH: usize = 32;
/// Authentication and association each get this long (wpa_supplicant's `SME_AUTH_TIMEOUT`).
const MLME_TIMEOUT: Duration = Duration::from_secs(5);
/// After association, how long the RPU gets to add the AP as a peer and turn the carrier on.
const LINK_TIMEOUT: Duration = Duration::from_secs(10);
/// How long the 4-way handshake may take once associated (wpa_supplicant gives it as long).
const HANDSHAKE_TIMEOUT: Duration = Duration::from_secs(10);
/// Longest event the driver reassembles. Longer ones are drained and dropped.
const MAX_EVENT_LEN: usize = 4096;

/// What a network is joined with.
