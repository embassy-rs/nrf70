        let mut known = KnownNetwork::new(Ssid::new(b"network").unwrap());
        assert_eq!((known.count, known.frequencies()), (0, [0; KNOWN_CHANNELS]));

        // Two access points on one channel count once, and the best channel comes first: 5 GHz
